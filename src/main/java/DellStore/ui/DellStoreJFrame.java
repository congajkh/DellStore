    private void phanQuyen() {
        System.out.println("Chức vụ đăng nhập: " + nvLogin.getChuc_vu());
    if (nvLogin == null) {
        JOptionPane.showMessageDialog(this, "Không có người dùng đăng nhập!", "Lỗi", JOptionPane.ERROR_MESSAGE);
        System.exit(0);
        return;
    }

    String chucVu = nvLogin.getChuc_vu() != null ? nvLogin.getChuc_vu().trim() : "";

    if (chucVu.equalsIgnoreCase("Nhân viên")) {
      btn_sanpham.setVisible(false);
btn_nhanvien.setVisible(false);
btn_khuyenmai.setVisible(false);
btn_thongke.setVisible(false);

    }

    lblTenNhanVien.setText("Xin chào: " + nvLogin.getTen_nv());
    lblChucVu.setText("Chức vụ: " + chucVu);
}


