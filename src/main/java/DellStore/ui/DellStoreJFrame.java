    private void btn_thoatActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_thoatActionPerformed
      int confirm = JOptionPane.showConfirmDialog(this, "Bạn có chắc chắn muốn đăng xuất?", "Đăng xuất", JOptionPane.YES_NO_OPTION);
      if (confirm == JOptionPane.YES_OPTION) {
        this.dispose(); // Đóng cửa sổ hiện tại

        // Gọi lại form đăng nhập và đưa ra giữa màn hình
        LoginJDialog login = new LoginJDialog(null, true);
        login.setLocationRelativeTo(null); // Đưa dialog ra giữa màn hình
        login.setVisible(true);

        // Nếu đăng nhập thành công thì mở lại JFrame chính với nhân viên vừa đăng nhập
        if (login.isLoggedIn()) {
            DellStoreJFrame main = new DellStoreJFrame(login.getNvLogin());
            main.setLocationRelativeTo(null); // Đưa JFrame ra giữa màn hình
            main.setVisible(true);
        }
    }
    }//GEN-LAST:event_btn_thoatActionPerformed

