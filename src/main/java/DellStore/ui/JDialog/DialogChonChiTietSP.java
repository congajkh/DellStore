    private void btn_xoaSPActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_xoaSPActionPerformed
        int row = tbl_bang.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn một sản phẩm để xóa!");
            return;
        }

        int ctspId = Integer.parseInt(tbl_bang.getValueAt(row, 0).toString()); // cột 0 = ctspId
        String maSerial = tbl_bang.getValueAt(row, 7).toString(); // cột 7 = Serial

        int confirm = JOptionPane.showConfirmDialog(this,
                "Bạn có chắc muốn xóa sản phẩm này?\nLưu ý: Các bản ghi liên quan sẽ bị xóa theo cascade nếu có.",
                "Xác nhận",
                JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        Connection conn = null;
        try {
            conn = XJdbc.openConnection();
            conn.setAutoCommit(false);

            // 1. Xóa Serial trước
            String sqlSerial = "DELETE FROM serial WHERE ctsp_id = ?";
            try (PreparedStatement ps = conn.prepareStatement(sqlSerial)) {
                ps.setInt(1, ctspId);
                ps.executeUpdate();
            }

            // 2. Xóa chi_tiet_dot_giam_gia trước (cascade sẽ xóa chi_tiet_hoa_don)
            String sqlCTDGG = "DELETE FROM chi_tiet_dot_giam_gia WHERE ctsp_id = ?";
            try (PreparedStatement ps = conn.prepareStatement(sqlCTDGG)) {
                ps.setInt(1, ctspId);
                ps.executeUpdate();
            }

            // 3. Xóa chi_tiet_san_pham
            String sqlCTSP = "DELETE FROM chi_tiet_san_pham WHERE id = ?";
            try (PreparedStatement ps = conn.prepareStatement(sqlCTSP)) {
                ps.setInt(1, ctspId);
                ps.executeUpdate();
            }

            // Commit transaction
            conn.commit();

            // 4. Cập nhật dialog
            dataList.removeIf(sp -> sp.getSerial().equals(maSerial));
            fillTable(dataList);

            JOptionPane.showMessageDialog(this, "Đã xóa sản phẩm thành công!");
        } catch (Exception e) {
            try {
                if (conn != null) {
                    conn.rollback();
                }
            } catch (SQLException ex) {
                ex.printStackTrace();
            }
            JOptionPane.showMessageDialog(this, "Xóa thất bại: " + e.getMessage());
            e.printStackTrace();
        } finally {
            try {
                if (conn != null) {
                    conn.close();
                }
            } catch (Exception ex) {
                ex.printStackTrace();
            }
        }
    }//GEN-LAST:event_btn_xoaSPActionPerformed
