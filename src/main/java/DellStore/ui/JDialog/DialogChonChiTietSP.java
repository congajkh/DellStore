    private void btn_xacnhanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_xacnhanActionPerformed
        int row = tbl_bang.getSelectedRow();
        if (row >= 0) {
            // Kiểm tra toàn bộ cột để đảm bảo không null
            for (int col = 0; col < tbl_bang.getColumnCount(); col++) {
                Object value = tbl_bang.getValueAt(row, col);
                if (value == null || value.toString().trim().isEmpty()) {
                    JOptionPane.showMessageDialog(this,
                            "Dữ liệu tại cột " + tbl_bang.getColumnName(col) + " đang trống!",
                            "Thiếu dữ liệu", JOptionPane.WARNING_MESSAGE);
                    return; // Thoát luôn, không xử lý tiếp
                }
            }

            selectedItem = new SanPhamChiTietViewModel();
            selectedItem.setId(Integer.parseInt(tbl_bang.getValueAt(row, 0).toString()));
            selectedItem.setTenSanPham(tbl_bang.getValueAt(row, 1).toString());
            selectedItem.setCpu(tbl_bang.getValueAt(row, 2).toString());
            selectedItem.setCard(tbl_bang.getValueAt(row, 3).toString());
            selectedItem.setHang(tbl_bang.getValueAt(row, 4).toString());
            selectedItem.setOcung(tbl_bang.getValueAt(row, 5).toString());
            selectedItem.setRam(tbl_bang.getValueAt(row, 6).toString());
            selectedItem.setSerial(tbl_bang.getValueAt(row, 7).toString());
            selectedItem.setGiaBan(new BigDecimal(tbl_bang.getValueAt(row, 8).toString()));

            String ttStr = tbl_bang.getValueAt(row, 9).toString();
            int tt = ttStr.equalsIgnoreCase("Đang Bán") ? 0 : 1;
            selectedItem.setTrangThai(tt);

            dispose(); // đóng dialog
        } else {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn một sản phẩm!");
        }
    }//GEN-LAST:event_btn_xacnhanActionPerformed

