    private void fillTable(List<SanPhamChiTietViewModel> list) {
        DefaultTableModel model = (DefaultTableModel) tbl_bang.getModel();
        model.setRowCount(0);
        for (SanPhamChiTietViewModel sp : list) {
            model.addRow(new Object[]{
                sp.getId(),
                sp.getTenSanPham(),
                sp.getCpu(),
                sp.getCard(),
                sp.getHang(),
                sp.getOcung(),
                sp.getRam(),
                sp.getSerial(),
                sp.getGiaBan(),
                sp.getTrangThai() == 0 ? "Đang bán" : "Đã bán"
            });
        }
    }

    private void filterData() {
        String keyword = txt_timkiemserial.getText().trim().toLowerCase();
        List<SanPhamChiTietViewModel> filtered = dataList.stream()
                .filter(sp -> sp.getSerial().toLowerCase().contains(keyword))
                .filter(sp -> {
                    if (rdo_dangban.isSelected()) {
                        return sp.getTrangThai() == 0;
                    }
                    if (rdo_daban.isSelected()) {
                        return sp.getTrangThai() == 1;
                    }
                    return true; // tất cả
                })
                .collect(Collectors.toList());

        fillTable(filtered);
    }

