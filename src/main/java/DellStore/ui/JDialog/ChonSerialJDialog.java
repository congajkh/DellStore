   public void loadTable(SanPham sp, List<Serial> listSerial) {
    // Khởi tạo model mới với tiêu đề chuẩn
    DefaultTableModel model = new DefaultTableModel(
        new Object[]{"Chọn", "Mã SP", "Tên SP", "Serial",
                     "SAN_PHAM_ID", "CPU_ID", "RAM_ID", "SSD_ID", "GPU_ID"}, 0
    ) {
        @Override
        public Class<?> getColumnClass(int columnIndex) {
            return columnIndex == 0 ? Boolean.class : Object.class;
        }

        @Override
        public boolean isCellEditable(int row, int column) {
            return column == 0; // chỉ cho tick checkbox
        }
    };

    // Đổ dữ liệu
    for (Serial s : listSerial) {
        ChiTietSanPham ctsp = ctspDAO.findById(s.getCtsp_id());
        if (ctsp != null) {
            model.addRow(new Object[]{
                false,
                sp.getMasp(),
                sp.getTen(),
                s.getMa_serial(),
                ctsp.getSan_pham_id(),
                ctsp.getCpu_id(),
                ctsp.getRam_id(),
                ctsp.getSsd_id(),
                ctsp.getGpu_id()
            });
        }
    }

    // Set model mới cho bảng
    tbl_bang.setModel(model);

    // Ẩn các cột thông số
    int[] hiddenCols = {4, 5, 6, 7, 8};
    for (int col : hiddenCols) {
        tbl_bang.getColumnModel().getColumn(col).setMinWidth(0);
        tbl_bang.getColumnModel().getColumn(col).setMaxWidth(0);
        tbl_bang.getColumnModel().getColumn(col).setWidth(0);
        tbl_bang.getColumnModel().getColumn(col).setPreferredWidth(0);
    }
}
