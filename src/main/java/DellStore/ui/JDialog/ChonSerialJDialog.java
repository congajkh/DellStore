    private void btn_xacnhanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_xacnhanActionPerformed
       selectedSerials.clear();
    DefaultTableModel model = (DefaultTableModel) tbl_bang.getModel();

    for (int i = 0; i < model.getRowCount(); i++) {
        Boolean isChecked = (Boolean) model.getValueAt(i, 0);
        if (isChecked != null && isChecked) {
            String serialStr = model.getValueAt(i, 3).toString();

            Serial s = serialDAO.findByMaSerial(serialStr);
            if (s != null) {
                // Check trùng: đã có Serial này trong giỏ (cthd) chưa?
                ChiTietSanPham ctsp = ctspDAO.findBySerialId(s.getId());

                if (ctsp != null && hoaDonDangTaoId != -1) {
                    ChiTietHoaDon cthdCu = cthdDAO.findByHoaDonAndCTSP(hoaDonDangTaoId, ctsp.getId());

                    if (cthdCu != null) {
                        // ❌ Trùng → bỏ qua hoặc thông báo
                        JOptionPane.showMessageDialog(this, "⚠️ Serial đã được chọn trước đó: " + serialStr);
                        continue;
                    }

                    // ✅ Chưa có → thêm mới vào chi tiết hóa đơn
                    ChiTietHoaDon cthd = new ChiTietHoaDon();
                    cthd.setHoa_don_id(hoaDonDangTaoId);
                    cthd.setChi_tiet_san_pham_id(ctsp.getId());
                    cthd.setSo_luong(1); // mỗi Serial chỉ 1 sản phẩm
                    cthd.setDon_gia(ctsp.getGia_ban());
                    cthd.setGiam_gia(BigDecimal.ZERO);
                    cthd.setTrang_thai(0);               
                    cthdDAO.insert(cthd);

                    // 🔄 Update trạng thái Serial sang "đang giữ" (2)
                    s.setTrang_thai(2);
                    serialDAO.updateTrangThai(s.getId(), s.getTrang_thai());

                    selectedSerials.add(s); // lưu Serial đã chọn
                    
                } else {
                    System.out.println("❌ Không thể lưu: ctsp = null hoặc hoaDonDangTaoId = -1");
                }
            }
        }
    }

    dispose(); // đóng dialog sau khi chọn xong
    }//GEN-LAST:event_btn_xacnhanActionPerformed

